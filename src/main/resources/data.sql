CREATE TABLE users (
          id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name VARCHAR(100) NOT NULL,
          surname VARCHAR(100),
          age INT,
          email VARCHAR(150) NOT NULL UNIQUE,
          password TEXT NOT NULL,
          phone_number VARCHAR(55),
          avatar TEXT,
          role_id INT NOT NULL,
          CONSTRAINT fk_user_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE TABLE vacancies (
           id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           name VARCHAR(255) NOT NULL,
           description TEXT NOT NULL,
           salary REAL,
           exp_from INT,
           exp_to INT,
           is_active BOOLEAN DEFAULT TRUE NOT NULL,
           created_date TIMESTAMP NOT NULL,
           update_time TIMESTAMP,
           category_id INT NOT NULL,
           user_id INT NOT NULL,
            CONSTRAINT fk_vacancy_category FOREIGN KEY (category_id) REFERENCES categories(id),
            CONSTRAINT fk_vacancy_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE resumes (
           id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           name VARCHAR(45) NOT NULL,
           salary REAL,
           is_active BOOLEAN NOT NULL,
           created_date TIMESTAMP NOT NULL,
           update_time TIMESTAMP,
           user_id INT NOT NULL,
           category_id INT NOT NULL,
           CONSTRAINT fk_resume_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
           CONSTRAINT fk_resume_category FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE TABLE contacts_info (
          id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          value TEXT NOT NULL,
          type_id INT NOT NULL,
          resume_id INT NOT NULL,
          CONSTRAINT fk_contact_info_type FOREIGN KEY (type_id) REFERENCES contact_types(id),
          CONSTRAINT fk_contact_info_resume FOREIGN KEY (resume_id) REFERENCES resumes(id) ON DELETE CASCADE
);

