CREATE TABLE roles (
         id INT PRIMARY KEY,
         role_name VARCHAR(20) NOT NULL,

         CONSTRAINT chk_id_values CHECK (id IN (1, 2)),
         CONSTRAINT chk_role_type_values CHECK (role_name IN ('applicant', 'employer'))
);

